import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const projectRoot = process.cwd();
const extensionDir = path.join(projectRoot, "browser-extension");
const appLibraryDir = path.join(projectRoot, "src", "app", "lib");
const registry = JSON.parse(
  readFileSync(path.join(projectRoot, "scrapers", "supported_sites.json"), "utf8")
).sites;

const publicSites = registry.map(({ name, site, hostname, baseUrl, aliases = [] }) => ({
  name,
  site,
  hostname,
  baseUrl,
  aliases,
}));

const hosts = [
  ...new Set(
    registry.flatMap(({ hostname, aliases = [] }) => [hostname, ...aliases])
  ),
].sort();

mkdirSync(extensionDir, { recursive: true });
mkdirSync(appLibraryDir, { recursive: true });
writeFileSync(
  path.join(extensionDir, "supported-sites.js"),
  `// Generated by scripts/build-browser-extension.mjs.\nself.MYCART_SUPPORTED_SITES = ${JSON.stringify(publicSites, null, 2)};\nself.MYCART_SUPPORTED_HOSTS = ${JSON.stringify(hosts, null, 2)};\n`
);
writeFileSync(
  path.join(appLibraryDir, "supportedSites.generated.js"),
  `// Generated by scripts/build-browser-extension.mjs.\nexport const SUPPORTED_STORES = ${JSON.stringify(publicSites, null, 2)};\n`
);
console.log(
  `Wrote ${publicSites.length} supported stores and ${hosts.length} extension hostnames.`
);
